export function getRecipesForCountry(countryCode: string): Recipe[] {
  return RECIPE_BANK[countryCode] ?? [];
}

export function pickRecipe(countryCode: string, exclude?: string): Recipe | null {
  const recipes = getRecipesForCountry(countryCode).filter(r => r.id !== exclude);
  if (!recipes.length) return null;
  return recipes[Math.floor(Math.random() * recipes.length)];
}
